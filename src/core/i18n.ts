const TABLES: Record<Lang, Record<string, string>> = { en: EN, ru: RU }

let current: Lang = "ru"

export function loadLangFromStorage(): void {
  const v = localStorage.getItem(BALANCE.LANG_KEY)
  if (v === "ru" || v === "en") current = v
}

export function getLang(): Lang {
  return current
}

export function setLang(lang: Lang): void {
  current = lang
  localStorage.setItem(BALANCE.LANG_KEY, lang)
}

export function t(key: string): string {
  return TABLES[current][key] ?? TABLES.en[key] ?? key
}

export function diffName(id: string): string {
  return t(`diff.${id}`)
}
